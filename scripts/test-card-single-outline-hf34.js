'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..');
const css=fs.readFileSync(path.join(root,'app/styles.css'),'utf8');
const js=fs.readFileSync(path.join(root,'app/games.js'),'utf8');
const tail=css.slice(css.indexOf('/* Hotfix 34 — one outline'),css.indexOf('/* Hotfix 35 — one *neutral cyan* outline'));
assert.ok(tail.length>500,'Hotfix 34 CSS exists');
assert.match(tail,/\.kinoteka-film-card\.is-selected \.kinoteka-card-poster\{[^}]*border-color:transparent!important/s);
assert.match(tail,/\.kinoteka-film-card\.is-selected \.kinoteka-card-poster::before\{[^}]*border-color:transparent!important/s);
assert.match(tail,/\.kinoteka-film-card\.is-selected::after\{[^}]*border-color:color-mix/s);
assert.match(tail,/\.kinoteka-film-card \.kinoteka-card-title\{[^}]*-webkit-line-clamp:3/s);
assert.match(tail,/\.kinoteka-film-card \.kinoteka-card-title-full\{/);
assert.match(tail,/\.kinoteka-card-title\.is-truncated:hover \+ \.kinoteka-card-title-full/);
assert.match(tail,/\.kinoteka-film-card:focus-visible \.kinoteka-card-title\.is-truncated \+ \.kinoteka-card-title-full/);
assert.match(js,/class="kinoteka-card-title-full" role="tooltip"/);
assert.match(js,/kinotekaCardGrid\.querySelectorAll\('\.kinoteka-card-title'\)/);
const from=js.indexOf('function refreshKinotekaCardTitles(){');
const to=js.indexOf('function scheduleKinotekaCardTitleCheck()',from);
assert.ok(from>0&&to>from);
const measured={truncated:false,title:'A Very Long Movie Title',attr:null};
const elm={scrollHeight:96,clientHeight:56,textContent:measured.title,
  classList:{toggle(name,bool){assert.equal(name,'is-truncated');measured.truncated=bool;}},
  removeAttribute(name){measured.attr=null;},setAttribute(name,val){measured.attr=val;}};
const ctx={kinotekaCardGrid:{querySelectorAll:()=>[elm]},kinotekaViewMode:'cards'};
vm.runInNewContext(js.slice(from,to)+';refreshKinotekaCardTitles();',ctx);
assert.equal(measured.truncated,true);
assert.equal(measured.attr,null,'no duplicate native tooltip');
elm.scrollHeight=56;
vm.runInNewContext('refreshKinotekaCardTitles()',ctx);
assert.equal(measured.truncated,false);
assert.equal(measured.attr,measured.title);
assert.match(js,/if\(typeof scheduleKinotekaCardTitleCheck==='function'\)scheduleKinotekaCardTitleCheck\(\)/);
assert.match(js,/document\.fonts\?\.ready/);
assert.match(js,/window\.addEventListener\('resize',scheduleKinotekaCardTitleCheck/);
assert.match(js,/event\.target\.closest\('\.kinoteka-card-title'\)/,'click-to-copy preserved');
assert.match(js,/document\.addEventListener\('keydown',handleSelectedCardPasteShortcut,true\)/);
assert.match(js,/document\.addEventListener\('keydown',handleSelectedCardCopyShortcut,true\)/);
assert.doesNotMatch(tail,/\.kinoteka-card-grid\{|\.kinoteka-card-score\{|\.kinoteka-card-type\{/,'grid, scores and icons untouched');
console.log('HOTFIX 34: PASS (single focus outline, 3-line titles, clipped full-name popup, resize/font relayout, copy + paste unchanged)');
