'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const rust=read('src-tauri/src/posters.rs');
const lib=read('src-tauri/src/lib.rs');
const bridge=read('app/shared/kinoteka-bridge.js');
const games=read('app/games.js');
const styles=read('app/styles.css');
const cargo=read('src-tauri/Cargo.toml');
const release=read('src-tauri/tauri.release.conf.json');
for(const call of ['poster_get','poster_set','poster_remove'])assert.ok(lib.includes(call),`Tauri IPC missing ${call}`);
assert.match(rust,/poster_directory\(\)/);
assert.match(rust,/Sha256::digest\(key\.as_bytes\(\)\)/);
assert.match(rust,/MAX_BYTES: usize = 5 \* 1024 \* 1024/);
assert.match(rust,/STANDARD\.decode/);
assert.match(rust,/create_new\(true\)/);
assert.match(rust,/image\/png/);
assert.match(rust,/image\/jpeg/);
assert.match(rust,/image\/webp/);
assert.match(rust,/fn extension_and_mime/);
assert.match(rust,/fn key_hash/);
assert.doesNotMatch(rust,/reqwest|Command::new|curl\.exe/i);
assert.match(rust,/commons\.wikimedia\.org/);
assert.match(rust,/credit_file/);
assert.match(cargo,/base64 = "0\.22\.1"/);
assert.match(cargo,/sha2 = "0\.10\.9"/);
assert.match(bridge,/getPosterKeyFor: entry/);
assert.match(bridge,/`imdb:\$\{imdb\}`/);
assert.match(bridge,/`local:\$\{encodeURIComponent\(identity\)\}`/);
assert.match(games,/posterChooser\.accept='image\/jpeg,image\/png,image\/webp/);
assert.match(games,/posterInvoke\('poster_set'/);
assert.match(games,/posterInvoke\('poster_get'/);
assert.match(games,/posterInvoke\('poster_remove'/);
assert.match(styles,/\.kinoteka-poster-image/);
assert.match(styles,/object-fit:cover/);
assert.ok(!fs.existsSync(path.join(root,'posters')),'Distributed source must have no user poster folder');
assert.ok(JSON.parse(release).app.security.csp['img-src'].includes('data:'),'Poster display needs data URLs');
console.log('LOCAL POSTERS QA: PASS (safe formats, hashed names, offline IPC, IMDb/manual keys, no shipped images)');
