'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=(f)=>fs.readFileSync(path.join(root,f),'utf8');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
assert.equal(pkg.version,'1.2.1');
assert.equal(pkg.description,'Kinoteka Standalone v1.2.1 Stable — HF60 Verified');
assert.equal(lock.version,'1.2.1');
assert.equal(lock.packages[''].version,'1.2.1');
assert.equal(lock.packages[''].description,pkg.description);
for(const f of ['src-tauri/tauri.conf.json','src-tauri/tauri.release.conf.json'])assert.equal(JSON.parse(read(f)).version,'1.2.1');
assert.match(read('src-tauri/Cargo.toml'),/name = "kinoteka-standalone"\nversion = "1\.2\.1"/);
assert.match(read('src-tauri/Cargo.lock'),/\[\[package\]\]\nname = "kinoteka-standalone"\nversion = "1\.2\.1"/);
const build=read('BUILD-RELEASE-v1.2.1.ps1');
const make=read('MAKE-FINAL-RELEASE-v1.2.1.ps1');
assert.match(build,/Kinoteka_Standalone_v1\.2\.1_Stable/);
assert.match(build,/CARGO_NET_OFFLINE = 'true'/);
assert.match(build,/npm_config_offline = 'true'/);
assert.doesNotMatch(build,/\bnpm ci\s*\n/);
assert.match(make,/Kinoteka_v1\.2\.1_Stable/);
assert.match(make,/BUILD-RELEASE-v1\.2\.1\.ps1/);
for (const check of ['RELEASE_NOTES_v1.2.1_STABLE.md','scripts/test-release-v121.js','MAKE-FINAL-RELEASE-v1.2.1.ps1','SHA256SUMS.txt','source_sha256 = $sourceHash','portable_sha256 = $portableHash','version = \'1.2.1\'','release = \'v1.2.1 Stable (HF60)\'','verify-release-artifact.js']) assert(make.includes(check)||fs.existsSync(path.join(root,check)),check);
assert.match(make,/if \(Test-Path -LiteralPath \$artifacts\)/);
assert.match(make,/if \(Test-Path -LiteralPath \$portable\)/);
assert.match(make,/New-ZipFromDirectory/);
assert.match(make,/Expand-ZipToDirectory/);
for (const name of ['BUILD-RELEASE-v1.2.1.cmd','MAKE-FINAL-RELEASE-v1.2.1.cmd']) assert(fs.existsSync(path.join(root,name)),name);
assert.match(read('RELEASE_NOTES_v1.2.1_STABLE.md'),/HF60/);
console.log('v1.2.1 STABLE RELEASE: PASS (version lockstep, offline build, clean packaging, SHA-256, HF60 provenance)');
