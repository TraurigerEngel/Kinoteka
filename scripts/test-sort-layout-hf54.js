'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'app/index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'app/styles.css'),'utf8');
const head=html.slice(0,html.indexOf('</head>'));
const desk=head.match(/\.toolbar\{\s*grid-template-columns:([^;]*);/);
assert(desk,'Missing head grid');
assert.match(desk[1],/minmax\(0,1fr\) max-content 225px 42px!important/);
assert.match(head,/\.toolbar \.resetFilters\{grid-column:4!important;grid-row:1!important/);
assert.match(head,/@media \(min-width:561px\) and \(max-width:900px\)/);
assert.match(head,/\.toolbar \.resetFilters\{grid-column:3!important;grid-row:1!important/);
assert.equal((head.match(/\.toolbar > \.kinoteka-sort-control\{grid-column:1 \/ 3!important;grid-row:3!important/g)||[]).length,2);
assert.doesNotMatch(head,/grid-auto-flow:column!important;/);
assert.match(css,/grid-template-columns:minmax\(0,1fr\) max-content 225px 42px!important/);
assert.match(css,/\.toolbar > \.resetFilters\{grid-column:4!important;grid-row:1!important/);
assert.match(css,/\.toolbar \.kinoteka-sort-control > \.kinoteka-reshuffle\[hidden\]\{display:none!important\}/);
assert.doesNotMatch(html,/id="kinotekaReshuffle"/);
assert.equal((html.match(/id="reset"/g)||[]).length,1);
assert.equal((html.match(/id="sort"/g)||[]).length,1);
