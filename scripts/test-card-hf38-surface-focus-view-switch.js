const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const css=fs.readFileSync(path.join(root,'app/styles.css'),'utf8');
const html=fs.readFileSync(path.join(root,'app/index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'app/games.js'),'utf8');
const added=css.split('/* Hotfix 38 — translucent empty posters')[1];
assert(added,'Hotfix 38 CSS should exist');
assert(added.includes('.kinoteka-card-poster:not(.has-poster)'),'only posters without images are translucent');
assert(added.includes('rgba(10,11,15,.61)'),'poster surface should use an alpha gradient');
assert(!added.includes('.kinoteka-poster-image{opacity'),'real poster pixels are not made transparent');
assert(added.includes('#kinotekaCardGrid:has(> .kinoteka-film-card.is-selected)'), 'dimming requires an explicitly selected card');
assert(added.includes('> .kinoteka-film-card:not(.is-selected)'), 'never dim selected card');
assert(added.includes('opacity:.74;'),'dim peers, not all cards');
assert(!added.includes('translateY(-4px)'),'do not reintroduce movement');
assert(added.includes('.kinoteka-viewbar .kinoteka-view-toggle') && added.includes('background:transparent;'),'remove old segmented capsule');
assert(added.includes('var(--active-filter-color,var(--total))'),'active view button follows the filter accent');
assert(html.includes('data-kinoteka-view="table"')&&html.includes('data-kinoteka-view="cards"'),'both view buttons exist');
assert(js.includes("card.classList.add('is-selected')"),'selection class remains available');
console.log('PASS Hotfix 38: empty poster alpha, selected isolation, view-toggle parity and stationary cards');
