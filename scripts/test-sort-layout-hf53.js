'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'app/index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'app/styles.css'),'utf8');
const selectJs=fs.readFileSync(path.join(root,'app/shared/themed-select.js'),'utf8');
const toolbar=html.match(/<div class="toolbar">([\s\S]*?)<\/div>\s*<div class="list-nav"/);
assert(toolbar,'Missing complete toolbar');
const t=toolbar[1];
assert.match(t,/<div class="kinoteka-sort-control"[^>]*>[\s\S]*?<select id="sort"/);
assert.match(t,/<\/select>\s*<\/div>/);
assert.doesNotMatch(t,/kinotekaReshuffle/);
assert(t.indexOf('kinoteka-sort-control')<t.indexOf('id="reset"'));
assert.equal((t.match(/id="sort"/g)||[]).length,1);
assert.equal((t.match(/id="kinotekaReshuffle"/g)||[]).length,0);
assert.match(css,/\.toolbar\s*>\s*\.kinoteka-sort-control\s*\{/);
assert.match(css,/grid-column:3!important;grid-row:1!important/);
assert.match(css,/\.toolbar\s*>\s*\.kinoteka-sort-control\s*>\s*\.kinoteka-select-shell/);
assert.match(css,/#sort:not\(\.kinoteka-native-select-source\)/,'Native fallback should be readable');
assert.match(css,/\.kinoteka-reshuffle\[hidden\]\{display:none!important\}/);
assert.match(css,/@media\(max-width:900px\)/);
assert.match(css,/grid-column:1 \/ 4!important;grid-row:2!important/);
assert.match(selectJs,/select\.insertAdjacentElement\('afterend', shell\)/);
assert.match(css,/grid-template-columns:minmax\(0,1fr\) max-content 225px 42px!important/);
console.log('HF53 SORT LAYOUT: PASS (dedicated slot, aligned row, fallback, no shuffle, responsive placement)');
