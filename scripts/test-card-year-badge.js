"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const games=fs.readFileSync(path.join(root,'app/games.js'),'utf8');
const css=fs.readFileSync(path.join(root,'app/styles.css'),'utf8');
const html=games.slice(games.indexOf('function renderCardView'),games.indexOf('if(kinotekaCardGrid)'));
assert.ok(html.length>1000);
assert.match(html,/const yearBadge=\/\^\\d\{4\}\$\/.test\(year\)/,'only display 4-digit years');
assert.match(html,/class="kinoteka-card-poster"[^>]+><div class="kinoteka-card-topline">\$\{yearBadge\}/,'year is on poster within aligned top row');
assert.match(html,/class="kinoteka-card-type/,'category icon is on poster');
assert.doesNotMatch(html,/class="kinoteka-card-subline"><span class="kinoteka-card-kind/,'category is no longer beneath the title');
assert.doesNotMatch(html,/class="kinoteka-card-subline"><span class="kinoteka-card-year"/);
assert.match(css,/\/\* Hotfix 23 — Real collection card readability/);
const polish=css.slice(css.indexOf('/* Hotfix 23 — Real collection card readability'));
assert.match(polish,/\.kinoteka-film-card \.kinoteka-card-title\{\s*font-size:14px;/);
assert.match(polish,/\-webkit-line-clamp:2/);
assert.match(polish,/\.kinoteka-card-poster \.kinoteka-card-year\{[\s\S]*?position:absolute;[\s\S]*?left:10px;/);
assert.match(polish,/\.kinoteka-poster-remove\{\s*left:auto;\s*right:49px;/);
assert.match(polish,/\.kinoteka-card-favorite:not\(\.is-on\):not\(:disabled\)/);
assert.match(html,/data-poster-choose/);
assert.match(html,/data-poster-remove/);
assert.match(html,/data-card-favorite/);
assert.match(html,/data-card-score/);
assert.match(games,/const pageSize=kinotekaViewMode==='cards'\?CARD_PAGE_SIZE:PAGE_SIZE/);
assert.doesNotMatch(html,/data-poster-auto/);
console.log('CARD YEAR BADGE QA: PASS (years above posters, readable names/stars, manual posters, unchanged pagination)');
