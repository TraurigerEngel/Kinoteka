"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const core=read('app/core.js'),games=read('app/games.js'),css=read('app/styles.css');
const cardMarkup=games.slice(games.indexOf('function renderCardView'),games.indexOf('if(kinotekaCardGrid)'));
assert.ok(cardMarkup.length>1000);
assert.doesNotMatch(cardMarkup,/kinoteka-poster-mark|const initial=|esc\(initial\)/,'no stray initial in poster placeholder');
assert.match(cardMarkup,/kinoteka-poster-caption[^>]*>KINOTEKA/,'clean brand placeholder');
assert.match(cardMarkup,/class="kinoteka-card-title" title="\$\{esc\(label\)\}"/,'full tooltip title retained');
assert.match(cardMarkup,/data-poster-choose/,'manual poster still available');
assert.match(cardMarkup,/data-card-favorite/,'favorite still available');
assert.match(cardMarkup,/data-card-score/,'unified score/status control available');
assert.doesNotMatch(cardMarkup,/data-card-rating/,'redundant status dropdown removed from cards');
assert.match(core,/const PAGE_SIZE=25;/);
assert.match(core,/const CARD_PAGE_SIZE=24;/);
assert.match(games,/const pageSize=kinotekaViewMode==='cards'\?CARD_PAGE_SIZE:PAGE_SIZE;/);
assert.match(games,/Math\.ceil\(filteredTotal\/pageSize\)/);
assert.match(games,/allRows\.slice\(\(currentPage-1\)\*pageSize,currentPage\*pageSize\)/);
assert.match(games,/currentPage=Math\.floor\(firstVisible\/newPageSize\)\+1/);
// Evaluate the exact switching and pagination arithmetic, not merely token presence.
const pageExpr=games.match(/const pageSize=kinotekaViewMode==='cards'\?CARD_PAGE_SIZE:PAGE_SIZE;[\s\S]*?const pageRows=allRows\.slice\(\(currentPage-1\)\*pageSize,currentPage\*pageSize\);/);
assert.ok(pageExpr,'pagination block found');
const evalPage=(count,mode,page)=>{
  const ctx={allRows:Array.from({length:count},(_,i)=>i),filteredTotal:count,kinotekaViewMode:mode,CARD_PAGE_SIZE:24,PAGE_SIZE:25,currentPage:page};
  vm.runInNewContext(pageExpr[0]+';global_result={totalPages,currentPage,pageRows}',ctx);
  return ctx.global_result;
};
assert.equal(evalPage(1122,'cards',1).pageRows.length,24);
assert.equal(evalPage(1122,'cards',1).totalPages,47);
assert.equal(evalPage(1122,'cards',47).pageRows.length,18);
assert.equal(evalPage(1122,'table',1).pageRows.length,25);
assert.equal(evalPage(1122,'table',1).totalPages,45);
assert.equal(evalPage(1122,'table',45).pageRows.length,22);
assert.equal(evalPage(0,'cards',42).currentPage,1);
const preserve=(oldPage,oldSize,newSize)=>Math.floor(((oldPage-1)*oldSize)/newSize)+1;
assert.equal(preserve(45,25,24),46);
assert.equal(preserve(47,24,25),45);
assert.match(css,/#listNav \.nav-controls\{column-gap:14px!important;gap:14px!important\}/);
assert.match(css,/kinoteka-card-poster:not\(\.has-poster\)\{gap:0\}/);
assert.match(css,/overflow-wrap:break-word/);
assert.match(css,/-webkit-line-clamp:2/);
assert.match(css,/\.kinoteka-film-card \.kinoteka-poster-mark\{display:none!important\}/);
assert.match(css,/kinoteka-commons-optin,\.kinoteka-poster-auto\{display:none!important\}/,'automatic posters remain paused');
console.log('REAL COLLECTION CARD POLISH QA: PASS (clean placeholders, 24 cards / 25 table, position mapping, two-line titles, controls)');
