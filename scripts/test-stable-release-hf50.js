'use strict';
const fs=require('fs');
const path=require('path');
const assert=require('assert/strict');
const root=path.resolve(__dirname,'..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
const configs=['src-tauri/tauri.conf.json','src-tauri/tauri.release.conf.json'];
assert.equal(pkg.version,'1.2.1');
assert.equal(lock.version,'1.2.1');
assert.equal(lock.packages[''].version,'1.2.1');
for(const f of configs) assert.equal(JSON.parse(read(f)).version,'1.2.1');
const cargo=read('src-tauri/Cargo.toml');
const cargolock=read('src-tauri/Cargo.lock');
assert.match(cargo,/\bversion = "1\.2\.1"/);
assert.match(cargolock,/\[\[package\]\]\r?\nname = "kinoteka-standalone"\r?\nversion = "1\.2\.1"/);
const builder=read('tools/legacy/BUILD-RELEASE.ps1');
const maker=read('tools/legacy/MAKE-FINAL-RELEASE.ps1');
assert.match(builder,/\$env:CARGO_NET_OFFLINE = 'true'/);
assert.match(builder,/\$env:npm_config_offline = 'true'/);
assert.match(builder,/\[switch\]\$SkipNpmCi = \$true/);
assert.doesNotMatch(builder,/^\s*npm ci\s*$/m);
assert.match(maker,/BUILD-RELEASE\.ps1'\) -SkipNpmCi/);
assert.match(maker,/Artifacts\\Kinoteka_v1\.2_Stable/);
assert.match(maker,/verify-release-artifact\.js/);
assert.match(maker,/\'docs\',\'tools\'/);
assert.match(maker,/SHA256SUMS\.txt/);
assert.match(maker,/source_sha256 = \$sourceHash/);
assert.match(maker,/portable_sha256 = \$portableHash/);
assert.ok(fs.existsSync(path.join(root,'docs/releases/RELEASE_NOTES_v1.2_STABLE.md')));
console.log('HF50 STABLE RELEASE: PASS (versions, offline build, clean distribution, SHA-256 and source ZIP guards)');
